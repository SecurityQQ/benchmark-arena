// The repository README carries a live "Open right now" table. Search engines index a GitHub page within hours and a
// new domain much later, so agents and people who land on the repo get the same picks as the site.
// Rewritten by the live and crawl workflows next to the data they commit: `npx tsx src/readme.ts`.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { CrawlResult } from "./types.js";
import { COMPUTE, boardsView } from "./prerender.js";
import { SITE } from "./render.js";
import { TOPICS } from "./topics.js";
import { CHALLENGES } from "./challenges.js";
import { loadPublished } from "./build.js";

export const START = "<!-- open-now:start: generated by src/readme.ts from the published data; edits here are overwritten -->";
export const END = "<!-- open-now:end -->";
const ROWS = 12;

// Crawled text from third-party repos: one line, no markup, no links of its own (bare URLs would be autolinked)
const cell = (s: unknown, max = 110) => {
  const t = String(s ?? "").replace(/\b(?:https?:\/\/|www\.)\S*/gi, "").replace(/\s+/g, " ").trim();
  return (t.length > max ? `${t.slice(0, max - 1).trimEnd()}…` : t).replace(/[\\`*_[\]<>!#|~]/g, (c) => `\\${c}`);
};
const n = (x: number) => x.toLocaleString("en-US");

export function openNowSection(data: Pick<CrawlResult, "crawledAt" | "competitions">, origin = SITE): string {
  const live = data.competitions.filter((c) => c.status !== "ended");
  const v = boardsView(live, data.crawledAt);
  const page = (id: string) => `${origin}/c/${encodeURIComponent(id)}`;
  const openTracks = (c: (typeof live)[number]) => c.problems.filter((p) => p.isOpen).length;
  return [
    START,
    `## Open right now`,
    ``,
    `${n(live.length)} active competitions, ${n(v.open.length)} open tracks, ${n(v.entries30)} entries in the last 30 days${v.byAgents30 ? ` (${n(v.byAgents30)} credited to an AI agent)` : ""}. Updated ${data.crawledAt.slice(0, 16).replace("T", " ")} UTC; the full list is at [openchallengelist.com](${origin}).`,
    ``,
    `| Challenge | What it is | Compute | Open tracks | Last 30 days |`,
    `|---|---|---|---|---|`,
    ...v.comps.slice(0, ROWS).map((c) => `| [${cell(c.name, 60)}](${page(c.id)}) | ${cell(c.tagline)} | ${COMPUTE[c.participation.compute] ?? "Compute not specified"} | ${openTracks(c) || "—"} | ${cell(v.recent.get(c.id), 140)} |`),
    ``,
    `Grand challenges: ${CHALLENGES.map((ch) => `[${ch.name}](${origin}/challenges/${ch.slug})`).join(" · ")}`,
    ``,
    `By topic: ${TOPICS.map((t) => `[${t.name}](${origin}/topics/${t.slug})`).join(" · ")} · [all ${n(live.length)}](${origin})`,
    END,
  ].join("\n");
}

export function withOpenNow(readme: string, section: string): string {
  const a = readme.indexOf("<!-- open-now:start"), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md: open-now markers missing or out of order");
  return readme.slice(0, a) + section + readme.slice(b + END.length);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = process.cwd(), path = join(root, "README.md");
  const before = readFileSync(path, "utf-8"), after = withOpenNow(before, openNowSection(loadPublished(root)));
  if (after !== before) writeFileSync(path, after);
  console.log(after === before ? "README.md: open-now unchanged" : "README.md: open-now updated");
}
